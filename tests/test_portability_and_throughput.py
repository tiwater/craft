"""Tests for cross-store portability checker and multi-order throughput evaluation."""
from __future__ import annotations

from pathlib import Path

from trax.benchmark import builtin_reference_policy_source
from trax.config import SceneConfig
from trax.host_driver import create_host_driver
from trax.portability import (
    check_policy_portability,
    evaluate_multi_order_throughput,
    simulate_pipeline_schedule,
)


HARDCODED_COORDS_POLICY = """def run_policy(sdk, params):
    obs = sdk.observe_scene()
    cup = obs["objects"][0]
    cup_xyz = cup["world"]
    already = abs(cup_xyz[0] - 0.45) < 0.09
    sdk.move_to_target([0.45, 0.0, 1.075], command_id="m1")
    return {"status": "completed", "url": "http://127.0.0.1:8795/cap"}
"""


def test_portability_checker_catches_hardcoded_coords_and_passes_clean_policies():
    # Built-in reference policy is cross-store portable
    ref_check = check_policy_portability(builtin_reference_policy_source())
    assert ref_check["portable"] is True
    assert ref_check["error_count"] == 0

    # Published v1 policy generated by TRAX is cross-store portable
    v1_path = (
        Path(__file__).resolve().parents[1]
        / "experiments"
        / "coffee-closed-loop-20261120"
        / "registry"
        / "releases"
        / "v1"
        / "policy.py"
    )
    v1_check = check_policy_portability(v1_path.read_text(encoding="utf-8"))
    assert v1_check["portable"] is True

    # Hardcoded coordinate literal, magic float subtraction, and endpoint URL are all caught
    bad_check = check_policy_portability(HARDCODED_COORDS_POLICY)
    assert bad_check["portable"] is False
    rules = {f["rule"] for f in bad_check["findings"]}
    assert "hardcoded_coordinate_literal" in rules
    assert "hardcoded_world_comparison" in rules
    assert "hardcoded_endpoint_or_path" in rules


def test_multi_order_throughput_and_pipeline_schedule_model():
    cfg = SceneConfig.from_file("examples/single_cup_coffee_config.json")
    data = cfg.to_dict()
    data["budget"]["deployment_scope"] = "fixture"
    data["budget"]["allow_live_actuation"] = True
    data["budget"]["allow_sim_reset"] = True
    drv = create_host_driver("fixture", SceneConfig.from_dict(data))

    batch = [
        {"preset": "default", "order_id": f"A{i:03d}", "expect_status": "completed"}
        for i in range(1, 5)
    ]
    res = evaluate_multi_order_throughput(drv, builtin_reference_policy_source(), batch, policy_id="ref")
    assert res["total_orders"] == 4
    assert res["completed_orders"] == 4
    assert res["completion_rate"] == 1.0
    assert res["throughput_orders_per_hour"] > 0

    # Schedule model: 2 appliances (e.g. coffee machine + oven or dual spout) overlap appliance_busy_s
    sched = simulate_pipeline_schedule(
        num_orders=10,
        robot_prep_s=6.0,
        appliance_busy_s=15.0,
        robot_deliver_s=6.0,
        appliance_slots=2,
    )
    assert sched["evidence_source"] == "schedule_model_from_measured_steps"
    assert sched["pipelined_orders_per_hour"] > sched["serial_orders_per_hour"]
    assert sched["projected_throughput_gain_pct"] > 30.0
